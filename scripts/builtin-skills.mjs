import { mkdir, readFile, readdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "skills");
const output = path.join(
  root,
  "server/internal/skills/builtin/bundle.generated.json",
);
const catalog = JSON.parse(
  await readFile(path.join(source, "catalog.json"), "utf8"),
);
const seenIDs = new Set();
const seenDirectories = new Set();
const skills = [];

// 按固定顺序打包完整目录，二进制资源和脚本执行位同样保留。
async function collect(directory, relative = "") {
  const files = [];
  const entries = await readdir(path.join(directory, relative), {
    withFileTypes: true,
  });
  entries.sort((a, b) => a.name.localeCompare(b.name, "en"));
  for (const entry of entries) {
    const name = relative ? `${relative}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await collect(directory, name)));
    } else if (entry.isFile()) {
      const file = path.join(directory, name);
      const data = await readFile(file);
      if (
        name.endsWith(".md") &&
        /\p{Script=Han}/u.test(data.toString("utf8"))
      ) {
        throw new Error(
          `Built-in skill Markdown must use English, including examples: ${name}`,
        );
      }
      files.push({
        path: name,
        data: data.toString("base64"),
        executable: ((await stat(file)).mode & 0o111) !== 0,
      });
    } else {
      throw new Error(`内置技能不支持软链接或特殊文件：${name}`);
    }
  }
  return files;
}

for (const definition of catalog) {
  const validID = /^[a-f0-9]{32}$/.test(definition.id);
  const validDirectory = /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(
    definition.directory,
  );
  const validVersion = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(
    definition.version,
  );
  if (
    !validID ||
    !validDirectory ||
    !validVersion ||
    seenIDs.has(definition.id) ||
    seenDirectories.has(definition.directory)
  ) {
    throw new Error(`内置技能清单无效或重复：${definition.directory}`);
  }
  seenIDs.add(definition.id);
  seenDirectories.add(definition.directory);
  const files = await collect(path.join(source, definition.directory));
  if (!files.some((file) => file.path === "SKILL.md")) {
    throw new Error(`内置技能缺少 SKILL.md：${definition.directory}`);
  }
  skills.push({ ...definition, files });
}
for (const entry of await readdir(source, { withFileTypes: true })) {
  if (entry.isDirectory() && !seenDirectories.has(entry.name)) {
    throw new Error(`技能目录尚未登记到 skills/catalog.json：${entry.name}`);
  }
}
skills.sort((a, b) => a.directory.localeCompare(b.directory, "en"));
const generated =
  JSON.stringify(
    {
      _generated:
        "Generated by pnpm skills:generate from skills/. Do not edit.",
      skills,
    },
    null,
    2,
  ) + "\n";
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8").catch(() => "")) !== generated) {
    throw new Error(
      "内置技能包与 skills/ 不一致，请运行 pnpm skills:generate。",
    );
  }
} else {
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, generated);
}
